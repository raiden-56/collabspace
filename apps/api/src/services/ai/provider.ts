import Anthropic from "@anthropic-ai/sdk";
import { config } from "../../config.js";
import { logger } from "../../lib/logger.js";

/**
 * AI provider adapter. All model calls go through here so the provider is configurable and
 * API keys never leave the server. Supported: "anthropic", "mock" (deterministic, offline), "disabled".
 */

export interface CompletionRequest {
  system: string;
  prompt: string;
  maxTokens?: number;
  /** Ask for a JSON object; the provider must return parseable JSON text. */
  json?: boolean;
}

export interface CompletionResult {
  text: string;
  inputTokens?: number;
  outputTokens?: number;
  model: string;
  provider: string;
}

export class AIProviderError extends Error {
  constructor(
    message: string,
    public code: "disabled" | "rate_limited" | "provider_error" | "invalid_output" | "not_configured",
    public retryable = false,
  ) {
    super(message);
  }
}

export interface AIProvider {
  readonly name: string;
  complete(req: CompletionRequest): Promise<CompletionResult>;
}

class AnthropicProvider implements AIProvider {
  readonly name = "anthropic";
  private client: Anthropic;
  constructor(apiKey: string) {
    this.client = new Anthropic({ apiKey });
  }
  async complete(req: CompletionRequest): Promise<CompletionResult> {
    try {
      const res = await this.client.messages.create({
        model: config.AI_MODEL,
        max_tokens: req.maxTokens ?? 2048,
        system: req.system + (req.json ? "\nRespond with a single JSON object and nothing else." : ""),
        messages: [{ role: "user", content: req.prompt }],
      });
      const text = res.content
        .filter((b): b is Anthropic.TextBlock => b.type === "text")
        .map((b) => b.text)
        .join("");
      return { text, inputTokens: res.usage.input_tokens, outputTokens: res.usage.output_tokens, model: res.model, provider: this.name };
    } catch (err) {
      const status = (err as { status?: number }).status;
      if (status === 429) throw new AIProviderError("The AI provider is rate limiting requests. Please try again shortly.", "rate_limited", true);
      if (status && status >= 500) throw new AIProviderError("The AI provider is temporarily unavailable.", "provider_error", true);
      logger.error({ err }, "Anthropic request failed");
      throw new AIProviderError((err as Error).message || "AI request failed", "provider_error", false);
    }
  }
}

/**
 * Deterministic offline provider used in development and tests. It performs simple heuristics
 * over the prompt so the full product flow (jobs, review UI, task conversion) works without a key.
 * Its output is clearly labeled as generated by the mock provider.
 */
class MockProvider implements AIProvider {
  readonly name = "mock";
  async complete(req: CompletionRequest): Promise<CompletionResult> {
    const source = extractSource(req.prompt);
    const lines = source.split(/\n+/).map((l) => l.trim()).filter(Boolean);
    let text: string;
    if (req.prompt.includes("TASK: meeting_summary")) {
      text = JSON.stringify(mockSummary(lines));
    } else if (req.prompt.includes("TASK: action_drafts")) {
      text = JSON.stringify({ actionItems: mockActions(lines) });
    } else if (req.prompt.includes("TASK: assistant")) {
      text = JSON.stringify(mockAssistant(req.prompt, lines));
    } else {
      text = `Summary (mock provider):\n${lines.slice(0, 5).join("\n")}`;
    }
    return { text, inputTokens: Math.ceil(req.prompt.length / 4), outputTokens: Math.ceil(text.length / 4), model: "mock-v1", provider: this.name };
  }
}

function extractSource(prompt: string): string {
  const m = prompt.match(/<source>([\s\S]*?)<\/source>/);
  return m ? m[1]!.trim() : prompt;
}

const ACTION_RE = /\b(will|can you|please|need to|needs to|should|i'll|i will|let's|action|todo|to do|follow up|by (monday|tuesday|wednesday|thursday|friday|saturday|sunday|next week|tomorrow|eod))\b/i;
const DECISION_RE = /\b(decision|decided|we go with|agreed|let's go with|we will ship|we ship)\b/i;
const QUESTION_RE = /\?\s*$|\bopen question\b/i;

function speaker(line: string): { who: string | null; text: string } {
  const m = line.match(/^([A-Z][\w .'-]{0,40}):\s*(.*)$/);
  return m ? { who: m[1]!, text: m[2]! } : { who: null, text: line };
}

function mockActions(lines: string[]) {
  const out: Array<{ text: string; suggestedOwner: string | null; suggestedDue: string | null; excerpt: string }> = [];
  for (const line of lines) {
    const { who, text } = speaker(line);
    if (!ACTION_RE.test(text) || DECISION_RE.test(text) || QUESTION_RE.test(text)) continue;
    const dueMatch = text.match(/by (monday|tuesday|wednesday|thursday|friday|saturday|sunday|next week|tomorrow|eod)/i);
    let owner: string | null = null;
    const youMatch = text.match(/^([A-Z][a-z]+),\s*can you/);
    if (youMatch) owner = youMatch[1]!;
    else if (/\b(i'll|i will|action for me)\b/i.test(text) && who) owner = who;
    out.push({ text: text.replace(/^(okay|ok|so|and)\s+/i, "").slice(0, 300), suggestedOwner: owner, suggestedDue: dueMatch ? dueMatch[1]!.toLowerCase() : null, excerpt: line.slice(0, 300) });
    if (out.length >= 12) break;
  }
  return out;
}

function mockSummary(lines: string[]) {
  const decisions = lines.filter((l) => DECISION_RE.test(l)).map((l) => ({ text: speaker(l).text.replace(/^(decision:)\s*/i, "").slice(0, 300), excerpt: l.slice(0, 300) }));
  const openQuestions = lines.filter((l) => QUESTION_RE.test(l)).map((l) => ({ text: speaker(l).text.replace(/^open question:\s*/i, "").slice(0, 300), excerpt: l.slice(0, 300) }));
  const actionItems = mockActions(lines);
  const participants = [...new Set(lines.map((l) => speaker(l).who).filter((w): w is string => Boolean(w)))];
  const topics = [
    { title: "Progress & status", points: lines.filter((l) => /progress|done|working|finished|shipped/i.test(l)).slice(0, 4).map((l) => speaker(l).text.slice(0, 200)) },
    { title: "Blockers & risks", points: lines.filter((l) => /blocker|blocked|risk|missing|problem/i.test(l)).slice(0, 4).map((l) => speaker(l).text.slice(0, 200)) },
    { title: "Next steps", points: actionItems.slice(0, 4).map((a) => a.text) },
  ].filter((t) => t.points.length);
  const recap = `Mock summary of ${lines.length} transcript lines${participants.length ? ` with ${participants.join(", ")}` : ""}. ${decisions.length} decision(s), ${actionItems.length} action item(s) and ${openQuestions.length} open question(s) were detected. Configure AI_PROVIDER=anthropic for a real language-model summary.`;
  return { recap, topics, decisions, openQuestions, actionItems, participants, generatedBy: "mock" };
}

function mockAssistant(prompt: string, lines: string[]) {
  const q = (prompt.match(/<question>([\s\S]*?)<\/question>/)?.[1] ?? "").trim();
  const overdue = lines.filter((l) => /overdue/i.test(l));
  let answer: string;
  if (/next|work on|priorit/i.test(q)) {
    const candidates = lines.filter((l) => /^TASK /.test(l) && !/done/i.test(l)).slice(0, 5);
    answer = candidates.length ? `Based on your open tasks (mock provider), consider these next:\n${candidates.map((c) => `• ${c.replace(/^TASK /, "")}`).join("\n")}` : "I could not find open tasks in the current context (mock provider).";
  } else if (/overdue/i.test(q)) {
    answer = overdue.length ? `Overdue items in your context:\n${overdue.map((c) => `• ${c.replace(/^TASK /, "")}`).join("\n")}` : "No overdue tasks were found in the current context.";
  } else if (/summar/i.test(q)) {
    answer = `Summary (mock provider) of the current context:\n${lines.slice(0, 8).map((l) => `• ${l.slice(0, 160)}`).join("\n")}`;
  } else {
    answer = `This is the offline mock assistant. I found ${lines.length} context lines relevant to your workspace. Ask me to summarize, list overdue tasks, or suggest what to work on next. Configure AI_PROVIDER=anthropic for full answers.`;
  }
  return { answer, proposedActions: [], generatedBy: "mock" };
}

class DisabledProvider implements AIProvider {
  readonly name = "disabled";
  async complete(): Promise<CompletionResult> {
    throw new AIProviderError("AI features are disabled on this server.", "disabled");
  }
}

let provider: AIProvider | undefined;

export function aiProvider(): AIProvider {
  if (provider) return provider;
  if (config.AI_PROVIDER === "anthropic") {
    if (!config.ANTHROPIC_API_KEY) {
      logger.warn("AI_PROVIDER=anthropic but ANTHROPIC_API_KEY is missing — AI features disabled");
      provider = new DisabledProvider();
    } else provider = new AnthropicProvider(config.ANTHROPIC_API_KEY);
  } else if (config.AI_PROVIDER === "mock") provider = new MockProvider();
  else provider = new DisabledProvider();
  return provider;
}

export function aiStatus() {
  const p = aiProvider();
  return { provider: p.name, enabled: p.name !== "disabled", model: p.name === "anthropic" ? config.AI_MODEL : p.name === "mock" ? "mock-v1" : null, dataSentToProvider: p.name === "anthropic" ? "Transcript text, meeting notes, and the resource text you explicitly include are sent to Anthropic when you run an AI action. Nothing is sent automatically." : "No data leaves this server." };
}

export function parseJson<T>(text: string): T {
  const trimmed = text.trim().replace(/^```(?:json)?/i, "").replace(/```$/, "").trim();
  try {
    return JSON.parse(trimmed) as T;
  } catch {
    const start = trimmed.indexOf("{");
    const end = trimmed.lastIndexOf("}");
    if (start >= 0 && end > start) {
      try {
        return JSON.parse(trimmed.slice(start, end + 1)) as T;
      } catch {
        /* fallthrough */
      }
    }
    throw new AIProviderError("The AI response could not be parsed. Please regenerate.", "invalid_output", true);
  }
}
